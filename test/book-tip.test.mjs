import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { bookTip } from "../scripts/book-tip.mjs";

function memoryJournal() {
  const rows = [];
  return {
    rows,
    record: (entry) => { rows.push(entry); return entry; },
    query: ({ category }) => rows.filter((row) => row.category === category),
  };
}

test("books a tip as a headed, balanced sidecar and records a journal receipt", () => {
  const dir = mkdtempSync(join(tmpdir(), "tips-book-"));
  const journal = memoryJournal();
  try {
    const receipt = { rail: "hive", provider: "hive", receiver: "emsenn0", amount: "5.000", currency: "HBD", receiptId: "tip-1", verifiedAt: "2026-09-05T12:00:00Z" };
    const result = bookTip(receipt, { sidecarPath: join(dir, "2026-09-05-tip-transactions.beancount"), journal });
    assert.equal(result.booked, true);
    const text = readFileSync(result.path, "utf8");
    assert.match(text, /^; Generated by scripts\/book-tip\.mjs \(@red-cup-engineering\/tips-services-section\)\. Do not hand-edit\./u);
    assert.match(text, /2026-09-05 open Assets:Digital-Assets:Hive:Custody:Emsenn0/u);
    assert.match(text, /2026-09-05 open Income:Tips:Hive/u);
    assert.match(text, /Assets:Digital-Assets:Hive:Custody:Emsenn0 {2}5\.000 HBD/u);
    assert.match(text, /Income:Tips:Hive {2}-5\.000 HBD/u);
    assert.equal(journal.rows.length, 1);
    assert.equal(journal.rows[0].record.receiptId, "tip-1");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("a second booking in the same day's file does not reopen already-open accounts", () => {
  const dir = mkdtempSync(join(tmpdir(), "tips-book-"));
  const journal = memoryJournal();
  const path = join(dir, "2026-09-05-tip-transactions.beancount");
  try {
    const first = { rail: "hive", provider: "hive", receiver: "emsenn0", amount: "5.000", currency: "HBD", receiptId: "tip-1", verifiedAt: "2026-09-05T12:00:00Z" };
    const second = { rail: "hive", provider: "hive", receiver: "emsenn0", amount: "2.000", currency: "HBD", receiptId: "tip-2", verifiedAt: "2026-09-05T13:00:00Z" };
    bookTip(first, { sidecarPath: path, journal });
    const result = bookTip(second, { sidecarPath: path, journal });
    assert.equal(result.accountsToOpen.length, 0);
    const text = readFileSync(path, "utf8");
    assert.equal((text.match(/open Income:Tips:Hive/gu) ?? []).length, 1);
    assert.match(text, /tip-1/u);
    assert.match(text, /tip-2/u);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("never re-opens an account a knownOpenPaths file (e.g. the main ledger) already opens", () => {
  const dir = mkdtempSync(join(tmpdir(), "tips-book-"));
  const journal = memoryJournal();
  const mainLedger = join(dir, "main-ledger.beancount");
  const sidecarPath = join(dir, "2026-09-05-tip-transactions.beancount");
  try {
    writeFileSync(mainLedger, "2026-08-27 open Assets:Digital-Assets:Hive:Custody:Emsenn0\n2026-08-27 open Income:Services\n");
    const receipt = { rail: "hive", provider: "hive", receiver: "emsenn0", amount: "1.000", currency: "HBD", receiptId: "tip-known-open", verifiedAt: "2026-09-05T12:00:00Z" };
    const result = bookTip(receipt, { sidecarPath, journal, knownOpenPaths: [mainLedger] });
    assert.equal(result.accountsToOpen.length, 1);
    assert.equal(result.accountsToOpen[0].account, "Income:Tips:Hive");
    const text = readFileSync(sidecarPath, "utf8");
    assert.doesNotMatch(text, /open Assets:Digital-Assets:Hive:Custody:Emsenn0/u);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("the sidecar is a projection of the journal: rebuilt whole, each receipt once", async () => {
  const { createSemanticRecordJournal } = await import("@red-cup-engineering/semiotic-eavt-services-section/record-semantic-record");
  const dir = mkdtempSync(join(tmpdir(), "tips-book-"));
  const path = join(dir, "2026-09-05-tip-transactions.beancount");
  try {
    const journal = createSemanticRecordJournal({ root: dir, objectKind: "tips.payment-service-record" });
    const first = { rail: "hive", provider: "hive", receiver: "emsenn0", amount: "5.000", currency: "HBD", receiptId: "tip-1", verifiedAt: "2026-09-05T12:00:00Z" };
    const second = { rail: "hive", provider: "hive", receiver: "emsenn0", amount: "2.000", currency: "HBD", receiptId: "tip-2", verifiedAt: "2026-09-05T13:00:00Z" };
    const nextDay = { ...second, receiptId: "tip-3", verifiedAt: "2026-09-06T09:00:00Z" };
    bookTip(first, { sidecarPath: path, journal, now: new Date("2026-09-05T12:00:01Z") });
    bookTip(nextDay, { sidecarPath: join(dir, "2026-09-06-tip-transactions.beancount"), journal, now: new Date("2026-09-06T09:00:01Z") });
    rmSync(path);
    bookTip(second, { sidecarPath: path, journal, now: new Date("2026-09-05T13:00:01Z") });
    const text = readFileSync(path, "utf8");
    assert.match(text, /tip-1[\s\S]*tip-2/u);
    assert.doesNotMatch(text, /tip-3/u);
    assert.equal((text.match(/open Income:Tips:Hive/gu) ?? []).length, 1);
    assert.equal(journal.query({ category: "tip-booking.transactions" }).filter((row) => row.record.receipt).length, 3);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
